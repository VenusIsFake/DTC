/**
 * Return a random question, optionally filtered by category and excluding already seen IDs.
 */
export function getRandomIcebreakerQuestion(
  category?: IcebreakerCategory | "all",
  excludeIds: number[] = []
): IcebreakerQuestion {
  const pool = ICEBREAKER_QUESTIONS.filter((q) => {
    if (category && category !== "all" && q.category !== category) return false;
    if (excludeIds.includes(q.id)) return false;
    return true;
  });

  if (pool.length === 0) {
    const fallbackPool =
      category && category !== "all"
        ? ICEBREAKER_QUESTIONS.filter((q) => q.category === category)
        : ICEBREAKER_QUESTIONS;
    return fallbackPool[Math.floor(Math.random() * fallbackPool.length)];
  }

  return pool[Math.floor(Math.random() * pool.length)];
}
